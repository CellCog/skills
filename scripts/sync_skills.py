#!/usr/bin/env python3
"""
Sync CellCog skills from the monorepo golden copy to this skills.sh distribution repo.

PURE COPY + VALIDATION — no content transformation. The golden SKILL.md files are
universal (their install sections speak to every channel: npx / OpenClaw / plugin /
manual), so this repo ships them verbatim. Design: multi-channel skill distribution
v3 (2026-08). Never edit skills/ here — edit the golden copy and re-run this script.

Golden copy: ../monorepo/md/cellcog/openclaw_skills/  (override with --source)
Target:      ./skills/

Usage:
    python3 scripts/sync_skills.py             # dry run - show what would change
    python3 scripts/sync_skills.py --execute   # copy + validate + regenerate README catalog
    python3 scripts/sync_skills.py --check     # exit 1 if repo differs from golden (CI-friendly)
"""

import argparse
import filecmp
import os
import re
import shutil
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SOURCE = os.path.normpath(
    os.path.join(REPO_ROOT, "..", "monorepo", "md", "cellcog", "openclaw_skills")
)
TARGET = os.path.join(REPO_ROOT, "skills")
README = os.path.join(REPO_ROOT, "README.md")
EXCLUDE_DIRS = {"__pycache__"}
CORE_SKILL = "cellcog"  # exempt from the npx-line check (it IS the install target)
CATALOG_START = "<!-- CATALOG:START (generated by scripts/sync_skills.py - do not edit) -->"
CATALOG_END = "<!-- CATALOG:END -->"


def discover(source):
    """Every directory in the golden copy that contains a SKILL.md is a skill."""
    skills = []
    for entry in sorted(os.listdir(source)):
        path = os.path.join(source, entry)
        if not os.path.isdir(path) or entry in EXCLUDE_DIRS:
            continue
        if os.path.isfile(os.path.join(path, "SKILL.md")):
            skills.append(entry)
    return skills


def read_frontmatter(skill_md_path):
    src = open(skill_md_path, encoding="utf-8").read()
    match = re.match(r"^---\n(.*?)\n---\n", src, re.S)
    fm = match.group(1) if match else ""
    name = re.search(r"^name:\s*(.+)$", fm, re.M)
    desc = re.search(r"^description:\s*(.+)$", fm, re.M)
    return (
        name.group(1).strip() if name else "",
        (desc.group(1).strip().strip('"') if desc else ""),
        src,
    )


def validate(source, skills):
    """Golden-copy invariants. Any error aborts the sync."""
    errors = []
    for skill in skills:
        name, desc, src = read_frontmatter(os.path.join(source, skill, "SKILL.md"))
        if name != skill:
            errors.append(f"{skill}: frontmatter name '{name}' != folder name")
        if not desc:
            errors.append(f"{skill}: empty description")
        if skill != CORE_SKILL and "npx skills add cellcog/skills" not in src:
            errors.append(f"{skill}: missing the universal npx install line")
    return errors


def copy_skill(source, skill):
    src_dir = os.path.join(source, skill)
    dst_dir = os.path.join(TARGET, skill)
    if os.path.isdir(dst_dir):
        shutil.rmtree(dst_dir)
    shutil.copytree(
        src_dir, dst_dir, ignore=shutil.ignore_patterns(*EXCLUDE_DIRS)
    )


def dirs_differ(source, skill):
    """True if the golden skill folder and the repo copy differ in any file."""
    src_dir = os.path.join(source, skill)
    dst_dir = os.path.join(TARGET, skill)
    if not os.path.isdir(dst_dir):
        return True
    cmp = filecmp.dircmp(src_dir, dst_dir, ignore=list(EXCLUDE_DIRS))
    if cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files:
        return True
    for sub in cmp.subdirs.values():
        if sub.left_only or sub.right_only or sub.diff_files or sub.funny_files:
            return True
    return False


def regenerate_catalog(source, skills):
    """Rewrite the README catalog table between the markers (drift-proof docs)."""
    rows = ["| Skill | Description |", "|---|---|"]
    for skill in skills:
        _, desc, _ = read_frontmatter(os.path.join(source, skill, "SKILL.md"))
        short = desc if len(desc) <= 160 else desc[:157] + "..."
        rows.append(f"| `{skill}` | {short} |")
    table = "\n".join(rows)
    readme = open(README, encoding="utf-8").read()
    pattern = re.compile(
        re.escape(CATALOG_START) + r".*?" + re.escape(CATALOG_END), re.S
    )
    if not pattern.search(readme):
        print("WARN: catalog markers not found in README.md - skipping catalog")
        return
    new_readme = pattern.sub(f"{CATALOG_START}\n{table}\n{CATALOG_END}", readme)
    open(README, "w", encoding="utf-8").write(new_readme)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default=DEFAULT_SOURCE)
    parser.add_argument("--execute", action="store_true", help="apply changes")
    parser.add_argument("--check", action="store_true", help="exit 1 on drift (CI)")
    args = parser.parse_args()

    source = os.path.abspath(args.source)
    if not os.path.isdir(source):
        print(f"ERROR: golden copy not found at {source}")
        sys.exit(2)

    skills = discover(source)
    print(f"Golden copy: {source}")
    print(f"Discovered {len(skills)} skills")

    errors = validate(source, skills)
    if errors:
        print("VALIDATION FAILED - nothing synced:")
        for e in errors:
            print(f"  - {e}")
        sys.exit(2)
    print("Validation: OK (folder==name, descriptions present, npx line present)")

    stale = [s for s in skills if dirs_differ(source, s)]
    extra = (
        [d for d in sorted(os.listdir(TARGET)) if os.path.isdir(os.path.join(TARGET, d)) and d not in skills]
        if os.path.isdir(TARGET)
        else []
    )

    if args.check:
        if stale or extra:
            print(f"DRIFT: {len(stale)} skill(s) differ from golden, {len(extra)} extra dir(s)")
            for s in stale:
                print(f"  ~ {s}")
            for d in extra:
                print(f"  + {d} (not in golden)")
            sys.exit(1)
        print("Check: repo matches golden. Clean.")
        sys.exit(0)

    if not stale and not extra:
        print("Nothing to do - repo matches golden.")
        return

    print(f"To sync: {len(stale)} skill(s)" + (f", to remove: {extra}" if extra else ""))
    if not args.execute:
        for s in stale:
            print(f"  would copy: {s}")
        print("Dry run only. Re-run with --execute to apply.")
        return

    os.makedirs(TARGET, exist_ok=True)
    for s in stale:
        copy_skill(source, s)
        print(f"  copied: {s}")
    for d in extra:
        shutil.rmtree(os.path.join(TARGET, d))
        print(f"  removed: {d}")
    regenerate_catalog(source, skills)
    print(f"Done. {len(skills)} skills in ./skills, README catalog regenerated.")


if __name__ == "__main__":
    main()
